// Regenerates the app icon from src/shared/brandMark.ts: icon.svg, icon.png (512, for Windows, Linux and
// the README) and icon.icns. macOS only (iconutil, sips); renders with Chrome.
// Run from apps/studio: node --no-warnings build/icon.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { MARK, markLayout, markStroke } from '../src/shared/brandMark.ts'

const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const f = (n) => n.toFixed(1)

/** The full icon on the 1024 canvas: macOS drop shadow, graphite tile, and the mark for `pt` points. */
export function iconSvg(pt) {
  const L = markLayout(pt)
  const pearl = (x, y, r) => `<circle cx="${f(x)}" cy="${f(y)}" r="${f(r)}" fill="url(#pearl)"/>`
  const term = ([x, y, r], fill) =>
    `<ellipse cx="${f(x)}" cy="${f(y + r * 0.62)}" rx="${f(r * 0.95)}" ry="${f(r * 0.45)}" fill="#000" opacity="0.3" filter="url(#soft)"/>` +
    `<circle cx="${f(x)}" cy="${f(y)}" r="${f(r)}" fill="${fill}"/>${pearl(x, y, r)}`
  const [rx, ry, rr] = L.result
  const mark =
    L.kind === 'stroke'
      ? `<path d="${markStroke}" fill="none" stroke="${MARK.ink}" stroke-width="${L.width}" stroke-linecap="round" stroke-linejoin="round"/>` +
        `<circle cx="${rx}" cy="${ry}" r="${rr}" fill="${MARK.result}"/>`
      : L.terms.map((t) => term(t, MARK.ink)).join('') +
        (L.ring ? `<circle cx="${f(rx)}" cy="${f(ry)}" r="${f(L.ring)}" fill="none" stroke="${MARK.result}" stroke-opacity="0.35" stroke-width="4"/>` : '') +
        term(L.result, MARK.result)
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Mathodology Studio app icon, generated by build/icon.mjs from src/shared/brandMark.ts (${pt} pt variant). -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0.35" y2="1"><stop offset="0" stop-color="${MARK.tile[0]}"/><stop offset="1" stop-color="${MARK.tile[1]}"/></linearGradient>
    <radialGradient id="light" cx="0.3" cy="0.08" r="0.9"><stop offset="0" stop-color="#fff" stop-opacity="0.1"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
    <radialGradient id="pearl" cx="0.36" cy="0.3" r="0.78"><stop offset="0" stop-color="#fff" stop-opacity="0.85"/><stop offset="0.22" stop-color="#fff" stop-opacity="0.18"/><stop offset="0.6" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="0.38"/></radialGradient>
    <filter id="soft" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="5"/></filter>
  </defs>
  <g fill="#000"><rect x="100" y="124" width="824" height="824" rx="185" opacity="0.05"/><rect x="100" y="110" width="824" height="824" rx="185" opacity="0.08"/></g>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#tile)"/>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="url(#light)"/>
  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" fill="none" stroke="rgba(255,255,255,0.1)" stroke-width="3"/>
  ${mark}
</svg>
`
}

function render(svg, out, tmp) {
  const html = join(tmp, 'icon.html')
  writeFileSync(html, `<!doctype html><html style="background:transparent"><body style="margin:0">${svg}</body></html>`)
  execFileSync(CHROME, ['--headless=new', '--disable-gpu', '--hide-scrollbars', '--default-background-color=00000000',
    `--user-data-dir=${join(tmp, 'chrome')}`, '--window-size=1024,1024', `--screenshot=${out}`, `file://${html}`], { stdio: 'ignore' })
}

if (import.meta.main) {
  const here = new URL('.', import.meta.url).pathname
  const tmp = mkdtempSync(join(tmpdir(), 'mathodology-icon-'))
  try {
    writeFileSync(join(here, 'icon.svg'), iconSvg(1024))
    // One master per optical variant; macOS picks the entry for the point size it draws.
    const masters = {}
    for (const pt of [16, 32, 1024]) render(iconSvg(pt), (masters[pt] = join(tmp, `m${pt}.png`)), tmp)
    execFileSync('sips', ['-z', '512', '512', masters[1024], '--out', join(here, 'icon.png')], { stdio: 'ignore' })
    const set = join(tmp, 'icon.iconset')
    mkdirSync(set)
    for (const pt of [16, 32, 128, 256, 512]) {
      for (const scale of [1, 2]) {
        const px = pt * scale
        const name = `icon_${pt}x${pt}${scale === 2 ? '@2x' : ''}.png`
        const src = masters[pt <= 16 ? 16 : pt <= 32 ? 32 : 1024]
        execFileSync('sips', ['-z', String(px), String(px), src, '--out', join(set, name)], { stdio: 'ignore' })
      }
    }
    execFileSync('iconutil', ['-c', 'icns', set, '-o', join(here, 'icon.icns')])
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}
